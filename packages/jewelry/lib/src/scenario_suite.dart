/// The one entry point every scenario file runs from, so the app is built
/// once and not once per file.
///
/// It imports each scenario file and hands them to `runScenarioSuite`, which
/// declares each file's tests in a group named after the file. On Android
/// the CLI picks a file at start through a system property; `flutter test
/// --name` picks one where the CLI cannot start the app itself.
/// Printed by the app once the picked file's scenarios are over:
/// `suiteDoneMarker\t<file>\t<number of failed scenarios>`.
const suiteDoneMarker = 'jewelry:done';

/// The Android system property the CLI sets to the scenario file to run,
/// as [ScenarioSuite.keyOf] names it.
const suiteProperty = 'debug.jewelry.scenario';

class ScenarioSuite {
  ScenarioSuite(Iterable<String> files)
    : files = ({for (final f in files) _clean(f)}.toList()..sort()) {
    for (final f in this.files) {
      if (!f.startsWith(_root)) {
        throw ArgumentError('$f: scenario files live under $_root');
      }
    }
  }

  static const _root = 'integration_test/';

  /// Where the CLI writes [source]. Under `integration_test/`, because the
  /// Flutter tool only runs files from there on a device.
  static const path = '${_root}jewelry_suite_test.dart';

  /// App-relative paths of every scenario file in the suite, sorted.
  final List<String> files;

  static String _clean(String file) =>
      file.startsWith('./') ? file.substring(2) : file;

  static String _group(String file) => _clean(file).substring(_root.length);

  /// The `--name` pattern that runs the scenarios of [file] and no others.
  static String nameOf(String file) => '^${RegExp.escape(_group(file))} ';

  String get source {
    final out = StringBuffer('''
// Generated by `jewelry run`, rewritten when the scenario files change.
// One entry point for every scenario, so the app is built once.
import 'package:jewelry/jewelry.dart';

''');
    for (final (i, f) in files.indexed) {
      out.writeln("import '${_group(f)}' as s$i;");
    }
    out.writeln('\nvoid main() => runScenarioSuite({');
    for (final (i, f) in files.indexed) {
      out.writeln("  '${_group(f)}': s$i.main,");
    }
    out.writeln('});');
    return out.toString();
  }

  /// What [suiteProperty] is set to for [file].
  static String keyOf(String file) => _group(file);
}
